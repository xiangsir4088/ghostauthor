"""Adoption diagnosis — why the ledger looks the way it does.

The audit answers "how many"; this module answers "why so few, and what do
I do about it". It exists because a provenance ledger has a cold-start
problem that no amount of accuracy can solve: if the agents in a repository
never wrote a `Co-Authored-By:` trailer, the audit is *correct* and
*useless* — every commit is `unsigned`, the ratio is 0.0, and the operator
concludes the tool is broken. It is not. The signatures are missing.

Two failure modes are distinguishable, and they have **different fixes**:

1. **The trailer was written, but the roster does not recognize it.**
   `Co-Authored-By: Cursor <cursoragent@cursor.com>` is a real signature;
   the builtin roster simply has no rule for that domain. The fix is data
   (`--roster` / `--roster-dir`), not code.
2. **No trailer was written at all.** The commit message carries a literal
   marker emitted by a known tool ("Generated with [Claude Code]"). The fix
   is the write path: `install-hook`, or the agent's own trailer setting.

A third case — no trailer, no marker — is *not* evidence of anything. It may
be a human commit, or an agent that leaves no trace. This module reports it
as silence, never as a conclusion. That distinction is the whole point of
the project: **the ledger records signatures, it does not guess.**

Determinism: like the audit, this is a pure function of `(commits, roster)`.
Periods are ISO weeks in UTC derived from `authored_at`; nothing reads the
wall clock, so the same repository state yields byte-identical output.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple

from .engine import attribute_commit
from .models import BUCKET_AGENT, BUCKET_COSIGNED, BUCKET_UNSIGNED, CommitInfo
from .options import apply_window
from .roster import Roster

# Deterministic markers that specific tools write when they do NOT emit a
# standard trailer. This is NOT style detection and NOT a classifier: every
# entry is a fixed literal (or a tight regex) that one named product emits.
# A hit is reported as a HINT with its exact matched line, never as an
# attribution — attribution remains trailer-only, by construction.
_KNOWN_MARKERS: Tuple[Tuple[str, str, Tuple[str, ...]], ...] = (
    ("claude-code", "Claude Code", (
        r"generated with \[?claude code\]?",
        r"🤖\s*generated with",
    )),
    ("cursor", "Cursor", (
        r"generated (?:by|with) cursor",
        r"cursor\s*agent",
        r"cursoragent@",
    )),
    ("copilot", "GitHub Copilot", (
        r"copilot-swe-agent",
        r"generated by copilot",
    )),
    ("codex", "OpenAI Codex", (
        r"openai codex",
        r"codex@openai\.com",
    )),
    ("aider", "Aider", (
        r"^aider:\s",
        r"\baider: ",
    )),
    ("gemini-cli", "Gemini CLI", (
        r"gemini[- ]cli",
        r"gemini-code-assist",
    )),
    ("windsurf", "Windsurf", (
        r"windsurf",
        r"codeium",
    )),
    ("devin", "Devin", (
        r"devin-ai",
        r"devin@",
    )),
)

_COMPILED_MARKERS = tuple(
    (agent_id, label,
     tuple(re.compile(p, re.IGNORECASE | re.MULTILINE) for p in patterns))
    for agent_id, label, patterns in _KNOWN_MARKERS
)

# A marker id names the PRODUCT that wrote the text; a roster id names the
# SIGNING IDENTITY the write path can use. They are not the same namespace,
# and conflating them produced a dead end: the diagnosis told a first-time
# user to run `install-hook --agent claude-code`, while the roster only knows
# `claude`, so the very first suggestion exited 2 with `sign-agent-unknown`.
# The mapping is data, and `None` means "the builtin roster has no signing
# identity for this tool" — the advice then becomes "add the rule first",
# never a command that cannot run.
_MARKER_ROSTER_ID: Dict[str, Optional[str]] = {
    "claude-code": "claude",
    "cursor": "cursor",
    "copilot": "copilot",
    "codex": "codex",
    "aider": "aider",
    "gemini-cli": "gemini",
    "windsurf": None,
    "devin": None,
}

# Adoption bands. Boundaries are pinned by tests (>= lower bound).
_ADOPTION_BANDS: Tuple[Tuple[float, str], ...] = (
    (0.8, "adopted"),   # most commits carry a roster-recognized signature
    (0.2, "partial"),   # enough signal to trust a trend, not enough for a gate
    (0.0, "minimal"),   # some signatures: the write path works, adoption is early
)


@dataclass(frozen=True)
class CoverageAuthor:
    """One author's signing behaviour.

    `commits` is the deduplicated row total; the three bucket counts sum to
    it, so the row is always internally consistent.
    """

    name: str
    email: str
    commits: int
    signed: int
    cosigned: int
    unsigned: int
    coverage_ratio: float


@dataclass(frozen=True)
class CoveragePeriod:
    """One ISO week (UTC), keyed `YYYY-Www`."""

    period: str
    commits: int
    signed: int
    coverage_ratio: float


@dataclass(frozen=True)
class CoverageSignal:
    """An unsigned commit whose message carries a known tool's literal
    marker. `sample_shas` keeps the traceability invariant: a count always
    expands to commits. `example` is the matched line, quoted verbatim."""

    agent_id: str
    label: str
    commits: int
    sample_shas: List[str]
    example: str


@dataclass(frozen=True)
class UnmatchedTrailer:
    """A trailer that IS a signature but no roster rule claims it.

    This is the cheapest possible fix — one roster entry — so it is reported
    separately from silence, with the exact raw line and its commit count.
    """

    trailer: str
    name: str
    email_domain: str
    commits: int
    sample_shas: List[str]


@dataclass(frozen=True)
class Action:
    """One recommended next step. `code` is stable (machine-readable);
    `detail` explains why; `command` is a copy-pasteable next move or ""."""

    code: str
    detail: str
    command: str


@dataclass(frozen=True)
class Coverage:
    """The complete, deterministic adoption diagnosis."""

    repo_path: str
    ref: str
    total_commits: int
    signed_commits: int
    coverage_ratio: float
    adoption: str
    buckets: Dict[str, int]
    by_author: List[CoverageAuthor]
    by_period: List[CoveragePeriod]
    signals: List[CoverageSignal]
    unmatched_trailers: List[UnmatchedTrailer]
    actions: List[Action]
    first_signed_at: Optional[int] = None
    last_signed_at: Optional[int] = None
    window: Optional[Dict] = None


def _period_key(ts: int) -> str:
    """ISO week in UTC. Deterministic: derived from the commit, not a clock."""
    iso = datetime.fromtimestamp(ts, timezone.utc).isocalendar()
    return f"{iso[0]:04d}-W{iso[1]:02d}"


def _ratio(n: int, total: int) -> float:
    return round(n / total, 6) if total else 0.0


def _adoption_band(ratio: float) -> str:
    for lower, label in _ADOPTION_BANDS:
        if ratio >= lower:
            return label
    return "none"


def build_coverage(commits: List[CommitInfo], roster: Roster,
                   repo_path: str = ".", ref: str = "HEAD",
                   since: Optional[int] = None,
                   until: Optional[int] = None) -> Coverage:
    """Attribute every commit once, then explain the gaps.

    Raises ValueError with the same window/empty codes as `build_report`
    (`window-invalid` / `no-commits` / `window-empty`), so a caller can
    treat both commands' failures identically — the filter and its codes
    come from the same `options.apply_window`.
    """
    windowed = apply_window(commits, since, until)
    ordered = sorted(windowed, key=lambda c: (c.authored_at, c.sha))

    buckets: Dict[str, int] = {BUCKET_AGENT: 0, BUCKET_COSIGNED: 0,
                               BUCKET_UNSIGNED: 0}
    authors: Dict[Tuple[str, str], Dict[str, int]] = {}
    periods: Dict[str, Dict[str, int]] = {}
    signals: Dict[str, Dict] = {}
    unmatched: Dict[str, Dict] = {}
    signed_ts: List[int] = []

    for c in ordered:
        bucket, _matched, _per = attribute_commit(c, roster)
        buckets[bucket] += 1

        row = authors.setdefault(
            (c.author_name, c.author_email),
            {"commits": 0, "agent": 0, "cosigned": 0, "unsigned": 0})
        row["commits"] += 1
        row[bucket] += 1

        period = periods.setdefault(
            _period_key(c.authored_at), {"commits": 0, "agent": 0})
        period["commits"] += 1

        if bucket == BUCKET_AGENT:
            signed_ts.append(c.authored_at)
            period["agent"] += 1
            continue

        if bucket == BUCKET_COSIGNED:
            # A real signature the roster does not claim: cheapest fix, so
            # report each distinct trailer once with its commit count.
            for t in c.trailers:
                if roster.match_detail(t.name, t.email_domain) is not None:
                    continue
                key = t.raw.strip()
                entry = unmatched.setdefault(
                    key, {"name": t.name, "domain": t.email_domain,
                          "commits": 0, "shas": []})
                entry["commits"] += 1
                if len(entry["shas"]) < 5:
                    entry["shas"].append(c.sha)
            continue

        # Unsigned: look for a literal marker left by a known tool. This is
        # a hint about *why* the trailer is missing, never an attribution.
        for agent_id, label, patterns in _COMPILED_MARKERS:
            hit = None
            for pattern in patterns:
                hit = pattern.search(c.message)
                if hit:
                    break
            if hit is None:
                continue
            entry = signals.setdefault(
                agent_id, {"label": label, "commits": 0, "shas": [],
                           "example": hit.group(0).strip()})
            entry["commits"] += 1
            if len(entry["shas"]) < 5:
                entry["shas"].append(c.sha)
            break  # one marker per commit keeps the counts honest

    total = len(ordered)
    signed = buckets[BUCKET_AGENT]
    ratio = _ratio(signed, total)
    # Zero is its own band: "minimal" would imply the convention started,
    # and the whole point of this command is to say that it has not.
    adoption = "none" if signed == 0 else _adoption_band(ratio)

    by_author = [
        CoverageAuthor(
            name=name, email=email, commits=data["commits"],
            signed=data[BUCKET_AGENT], cosigned=data[BUCKET_COSIGNED],
            unsigned=data[BUCKET_UNSIGNED],
            coverage_ratio=_ratio(data[BUCKET_AGENT], data["commits"]))
        for (name, email), data in sorted(authors.items())
    ]
    by_period = [
        CoveragePeriod(period=key, commits=data["commits"],
                       signed=data[BUCKET_AGENT],
                       coverage_ratio=_ratio(data[BUCKET_AGENT],
                                             data["commits"]))
        for key, data in sorted(periods.items())
    ]
    signal_list = [
        CoverageSignal(agent_id=aid, label=data["label"],
                       commits=data["commits"], sample_shas=data["shas"],
                       example=data["example"])
        for aid, data in sorted(signals.items(),
                                key=lambda kv: (-kv[1]["commits"], kv[0]))
    ]
    unmatched_list = [
        UnmatchedTrailer(trailer=raw, name=data["name"],
                         email_domain=data["domain"],
                         commits=data["commits"],
                         sample_shas=data["shas"])
        for raw, data in sorted(unmatched.items(),
                                key=lambda kv: (-kv[1]["commits"], kv[0]))
    ]

    return Coverage(
        repo_path=repo_path, ref=ref, total_commits=total,
        signed_commits=signed, coverage_ratio=ratio, adoption=adoption,
        buckets=buckets, by_author=by_author, by_period=by_period,
        signals=signal_list, unmatched_trailers=unmatched_list,
        actions=_actions(ratio, total, signed, signal_list, unmatched_list,
                         roster),
        first_signed_at=min(signed_ts) if signed_ts else None,
        last_signed_at=max(signed_ts) if signed_ts else None,
        window=({"since": since, "until": until}
                if (since is not None or until is not None) else None),
    )


def _roster_signing_id(roster: Roster, marker_id: str) -> Optional[str]:
    """The roster id that can actually sign for a marker, or None.

    Requires BOTH a mapped id and a `signing` identity on that rule: an id
    that exists but cannot sign would install a hook that fails at commit
    time, which is worse than saying "add a rule first".
    """
    target = _MARKER_ROSTER_ID.get(marker_id)
    if target is None:
        return None
    for agent in roster.agents:
        if agent.id == target and agent.signing is not None:
            return target
    return None


def _first_signable_id(roster: Roster) -> Optional[str]:
    """The first roster agent that can actually sign, or None.

    Deterministic (roster order) and only ids that HAVE a `signing`
    identity — naming an id that cannot sign would install a hook that
    fails at commit time, which is worse than saying "add a rule first".
    """
    for agent in roster.agents:
        if agent.signing is not None:
            return agent.id
    return None


def _actions(ratio: float, total: int, signed: int,
             signals: List[CoverageSignal],
             unmatched: List[UnmatchedTrailer],
             roster: Roster) -> List[Action]:
    """Turn the diagnosis into a short, ordered plan.

    Ordering is by leverage: a roster rule is data and takes one minute; the
    hook is structural; the gate is only safe once coverage is real. Every
    action is derived from measured facts — none is emitted speculatively.

    Every command must RUN against the roster the caller passed: a plan that
    exits 2 on its first step teaches a new user that the tool is broken.
    """
    out: List[Action] = []
    if unmatched:
        top = unmatched[0]
        out.append(Action(
            code="add-roster-rule",
            detail=(f"{top.commits} commit(s) carry the signature "
                    f"{top.trailer!r}, but no roster rule claims it. This is "
                    "a data fix, not a code change — add a rule for "
                    f"{top.name!r} / domain {top.email_domain!r}."),
            command="ghostauthor lint-roster --roster <your-roster.json>"))
    if signals:
        top = signals[0]
        signable = _roster_signing_id(roster, top.agent_id)
        if signable is not None:
            command = f"ghostauthor install-hook . --agent {signable}"
            tail = f"Sign at commit time with the hook (roster id: {signable})."
        else:
            # Honest advice beats a command that cannot run: the builtin
            # roster has no signing identity for this product, so the first
            # step is adding one, not installing a hook that would fail.
            command = "ghostauthor install-hook . --agent <agent-id>"
            tail = ("The roster has no signing identity for this tool yet — "
                    "add one rule for it, then install the hook with that "
                    "id (see docs/roster.md).")
        out.append(Action(
            code="install-hook",
            detail=(f"{top.commits} unsigned commit(s) carry a literal "
                    f"{top.label} marker ({top.example!r}) — the tool works, "
                    f"the trailer is simply not being written. {tail}"),
            command=command))
    if total and signed == 0:
        # A command that cannot run teaches a new user that the tool is
        # broken — so the placeholder `--agent <agent-id>` is only used
        # when NO roster agent can sign. Otherwise the roster's own
        # signable id is named, and the command works as printed.
        signable = _first_signable_id(roster)
        if signable is not None:
            command = f"ghostauthor install-hook . --agent {signable}"
            tail = (f" The roster's `{signable}` can sign today — use the "
                    "agent your commits actually come from.")
        else:
            command = "ghostauthor install-hook . --agent <agent-id>"
            tail = (" No roster agent has a signing identity yet — add one "
                    "rule first (see docs/roster.md), then install the hook "
                    "with that id.")
        out.append(Action(
            code="no-signatures",
            detail=("No commit in scope carries a roster-recognized "
                    "signature. Either this repository predates the "
                    "convention, or its agents do not emit standard trailers. "
                    "Start the convention at HEAD and let the ledger fill "
                    "forward — history is not rewritten." + tail),
            command=command))
    elif 0 < ratio < 0.8:
        out.append(Action(
            code="close-the-gap",
            detail=(f"{total - signed} of {total} commit(s) in scope are "
                    "unsigned. Partial adoption is the worst state to gate "
                    "on: the number moves for reasons unrelated to "
                    "behaviour. Close the gap before enforcing it."),
            command="ghostauthor coverage . --format json"))
    if ratio >= 0.8:
        out.append(Action(
            code="enforce-gate",
            detail=(f"Coverage is {ratio:.0%} — high enough that a gate "
                    "measures behaviour rather than adoption noise. Add "
                    "--max-ai-ratio to CI and make the number a contract."),
            command="ghostauthor . --max-ai-ratio 0.5"))
    return out


def render_coverage_json(cov: Coverage) -> str:
    """Canonical JSON: sorted keys, 2-space indent, UTF-8, trailing LF.

    Byte-stable for the same repository state, like every other read-side
    surface. `schema_version` is 1 and evolves additively (new keys only).
    """
    payload = {
        "schema_version": "1",
        "repo_path": cov.repo_path,
        "ref": cov.ref,
        "window": cov.window,
        "total_commits": cov.total_commits,
        "signed_commits": cov.signed_commits,
        "coverage_ratio": cov.coverage_ratio,
        "adoption": cov.adoption,
        "buckets": cov.buckets,
        "first_signed_at": cov.first_signed_at,
        "last_signed_at": cov.last_signed_at,
        "by_author": [
            {"name": a.name, "email": a.email, "commits": a.commits,
             "signed": a.signed, "cosigned": a.cosigned,
             "unsigned": a.unsigned, "coverage_ratio": a.coverage_ratio}
            for a in cov.by_author
        ],
        "by_period": [
            {"period": p.period, "commits": p.commits, "signed": p.signed,
             "coverage_ratio": p.coverage_ratio}
            for p in cov.by_period
        ],
        "signals": [
            {"agent_id": s.agent_id, "label": s.label, "commits": s.commits,
             "sample_shas": s.sample_shas, "example": s.example}
            for s in cov.signals
        ],
        "unmatched_trailers": [
            {"trailer": u.trailer, "name": u.name,
             "email_domain": u.email_domain, "commits": u.commits,
             "sample_shas": u.sample_shas}
            for u in cov.unmatched_trailers
        ],
        "actions": [
            {"code": a.code, "detail": a.detail, "command": a.command}
            for a in cov.actions
        ],
    }
    return json.dumps(payload, sort_keys=True, indent=2,
                      ensure_ascii=False) + "\n"


def render_coverage_text(cov: Coverage) -> str:
    """Terminal diagnosis: verdict first, then the evidence, then the plan."""
    lines: List[str] = []
    lines.append(f"ghostauthor coverage — {cov.repo_path}")
    lines.append(f"  scope: {cov.ref}"
                 + (f"   window: since={cov.window['since']} "
                    f"until={cov.window['until']}" if cov.window else ""))
    lines.append("")
    lines.append(f"  {cov.signed_commits} of {cov.total_commits} commits "
                 f"carry a recognized signature — {cov.coverage_ratio:.1%}")
    lines.append(f"  adoption: {cov.adoption.upper()}")
    lines.append("")
    lines.append("  buckets")
    for key in (BUCKET_AGENT, BUCKET_COSIGNED, BUCKET_UNSIGNED):
        lines.append(f"    {key:<10} {cov.buckets[key]:>6}")
    if cov.first_signed_at is not None:
        first = datetime.fromtimestamp(cov.first_signed_at,
                                       timezone.utc).strftime("%Y-%m-%d")
        last = datetime.fromtimestamp(cov.last_signed_at,
                                      timezone.utc).strftime("%Y-%m-%d")
        lines.append(f"  signed history: {first} .. {last} (UTC)")
    if cov.unmatched_trailers:
        lines.append("")
        lines.append("  signatures the roster does not recognize "
                     "(fix: add a roster rule)")
        for u in cov.unmatched_trailers[:5]:
            lines.append(f"    {u.commits:>4}x  {u.trailer}")
    if cov.signals:
        lines.append("")
        lines.append("  unsigned commits with a known tool marker "
                     "(hint, not attribution)")
        for s in cov.signals:
            lines.append(f"    {s.commits:>4}x  {s.label:<12} "
                         f"{s.example!r}")
    if cov.by_author:
        lines.append("")
        lines.append("  by author")
        for a in sorted(cov.by_author, key=lambda x: (-x.commits, x.email)):
            lines.append(f"    {a.coverage_ratio:>6.1%}  "
                         f"{a.commits:>4} commits  {a.name or a.email}")
    if cov.by_period:
        lines.append("")
        lines.append("  by ISO week (UTC)")
        for p in cov.by_period[-12:]:
            lines.append(f"    {p.period}  {p.signed:>3}/{p.commits:<3}  "
                         f"{p.coverage_ratio:>6.1%}")
    if cov.actions:
        lines.append("")
        lines.append("  next steps")
        for i, action in enumerate(cov.actions, 1):
            lines.append(f"    {i}. [{action.code}] {action.detail}")
            if action.command:
                lines.append(f"       $ {action.command}")
    lines.append("")
    return "\n".join(lines) + "\n"
